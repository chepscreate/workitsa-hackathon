#!/usr/bin/env node
/**
 * Build-time generator for public/firebase-messaging-sw.js.
 *
 * Service workers can't read process.env, so we bake the public Firebase
 * config into the SW file at build time. Reads .env.local for the config
 * values — same source of truth as the Next.js client.
 *
 * Runs automatically via the `prebuild` npm script.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const envPath = resolve(root, ".env.local");
const outPath = resolve(root, "public/firebase-messaging-sw.js");

if (!existsSync(envPath)) {
  console.warn(
    "[gen-firebase-messaging-sw] No .env.local found — skipping (push notifications will be disabled).",
  );
  process.exit(0);
}

const env = {};
for (const line of readFileSync(envPath, "utf8").split("\n")) {
  const trimmed = line.trim();
  if (!trimmed || trimmed.startsWith("#")) continue;
  const eq = trimmed.indexOf("=");
  if (eq < 0) continue;
  const key = trimmed.slice(0, eq).trim();
  let val = trimmed.slice(eq + 1).trim();
  if (
    (val.startsWith('"') && val.endsWith('"'))
    || (val.startsWith("'") && val.endsWith("'"))
  ) {
    val = val.slice(1, -1);
  }
  env[key] = val;
}

const required = [
  "NEXT_PUBLIC_FIREBASE_API_KEY",
  "NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN",
  "NEXT_PUBLIC_FIREBASE_PROJECT_ID",
  "NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET",
  "NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID",
  "NEXT_PUBLIC_FIREBASE_APP_ID",
];
const missing = required.filter((k) => !env[k]);
if (missing.length > 0) {
  console.warn(
    `[gen-firebase-messaging-sw] Missing env vars: ${missing.join(", ")} — skipping SW generation.`,
  );
  process.exit(0);
}

const sw = `/* AUTO-GENERATED by scripts/gen-firebase-messaging-sw.mjs — do not edit. */
/* eslint-disable */
importScripts("https://www.gstatic.com/firebasejs/10.13.2/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/10.13.2/firebase-messaging-compat.js");

firebase.initializeApp({
  apiKey: ${JSON.stringify(env.NEXT_PUBLIC_FIREBASE_API_KEY)},
  authDomain: ${JSON.stringify(env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN)},
  projectId: ${JSON.stringify(env.NEXT_PUBLIC_FIREBASE_PROJECT_ID)},
  storageBucket: ${JSON.stringify(env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET)},
  messagingSenderId: ${JSON.stringify(env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID)},
  appId: ${JSON.stringify(env.NEXT_PUBLIC_FIREBASE_APP_ID)},
});

const messaging = firebase.messaging();

// Background message handler — fires when the tab is closed / backgrounded.
// Foreground messages are handled in the client via onMessage().
messaging.onBackgroundMessage((payload) => {
  const title = (payload.notification && payload.notification.title) || "Workit";
  const body = (payload.notification && payload.notification.body) || "";
  const data = payload.data || {};
  self.registration.showNotification(title, {
    body,
    icon: "/icon-192.png",
    badge: "/icon-192.png",
    data,
    tag: data.tag || undefined,
  });
});

// When the user taps a notification, open the linked URL (or the app root).
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const href = (event.notification.data && event.notification.data.href) || "/";
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((list) => {
      for (const client of list) {
        try {
          const url = new URL(client.url);
          if (url.pathname === href || url.href.endsWith(href)) {
            return client.focus();
          }
        } catch (_) { /* ignore */ }
      }
      return self.clients.openWindow(href);
    }),
  );
});
`;

writeFileSync(outPath, sw, "utf8");
console.log(`[gen-firebase-messaging-sw] Wrote ${outPath}`);
